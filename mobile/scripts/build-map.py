"""Build the app's Gujarat district map from the website's GeoJSON (geoBoundaries, ODbL).

Projects longitude and latitude onto a flat SVG (scaled by cos(latitude) so shapes aren't
stretched), simplifies each outline (Douglas-Peucker) so the file stays small, and writes
src/components/gujarat-paths.ts. Run: python3 scripts/build-map.py
"""

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "web" / "public" / "geo" / "gujarat-districts.geojson"
OUT = ROOT / "src" / "components" / "gujarat-paths.ts"
WIDTH = 1000
TOLERANCE = 1.6  # in output units; smaller keeps more detail


def rings(geometry):
    polys = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
    for poly in polys:
        yield poly[0]  # outer ring only; Gujarat districts have no meaningful holes at this scale


def simplify(points, tol):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    best, idx = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [points[0], points[-1]]
    return simplify(points[: idx + 1], tol)[:-1] + simplify(points[idx:], tol)


def main():
    data = json.loads(SRC.read_text())
    lons = [p[0] for f in data["features"] for r in rings(f["geometry"]) for p in r]
    lats = [p[1] for f in data["features"] for r in rings(f["geometry"]) for p in r]
    k = math.cos(math.radians((min(lats) + max(lats)) / 2))
    x0, x1, y0, y1 = min(lons) * k, max(lons) * k, min(lats), max(lats)
    scale = WIDTH / (x1 - x0)
    height = round((y1 - y0) * scale)

    def project(lon, lat):
        return (lon * k - x0) * scale, (y1 - lat) * scale

    out, kept = [], 0
    for f in data["features"]:
        parts = []
        for ring in rings(f["geometry"]):
            ring_pts = [project(*p[:2]) for p in ring]
            # A closed ring starts and ends on one point, which Douglas-Peucker can't split on,
            # so simplify it as two halves.
            half = len(ring_pts) // 2
            pts = simplify(ring_pts[: half + 1], TOLERANCE)[:-1] + simplify(ring_pts[half:], TOLERANCE)
            if len(pts) < 4:
                continue
            kept += len(pts)
            parts.append("M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in pts) + "Z")
        cx, cy = project(f["properties"]["lon"], f["properties"]["lat"])
        out.append({"name": f["properties"]["name"], "d": "".join(parts), "cx": round(cx), "cy": round(cy)})

    body = ",\n".join(f"  {json.dumps(d, separators=(',', ':'))}" for d in sorted(out, key=lambda d: d["name"]))
    OUT.write_text(
        "// Generated by scripts/build-map.py from web/public/geo/gujarat-districts.geojson\n"
        "// (geoBoundaries, ODbL). Do not edit by hand.\n"
        f"export const MAP_VIEWBOX = {{ width: {WIDTH}, height: {height} }};\n\n"
        "export const DISTRICT_PATHS: { name: string; d: string; cx: number; cy: number }[] = [\n"
        f"{body},\n];\n"
    )
    print(f"{len(out)} districts, {kept} points, {OUT.stat().st_size // 1024} KB, {WIDTH}x{height}")


if __name__ == "__main__":
    main()
