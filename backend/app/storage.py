"""Where proof photos are kept: local disk (development, tests) or Supabase Storage.

Both backends store an object under a random name and read it back for the admin
review screen. Photos are never public: Supabase objects live in a private bucket
and are fetched server-side with the service key.
"""

import uuid
from pathlib import Path
from typing import Protocol

import httpx

from app.config import get_settings


class StorageError(Exception):
    pass


class ProofStorage(Protocol):
    async def save(self, data: bytes, media_type: str, suffix: str) -> str: ...
    async def load(self, name: str) -> bytes: ...


class LocalStorage:
    def __init__(self, directory: str):
        self.directory = Path(directory)

    async def save(self, data: bytes, media_type: str, suffix: str) -> str:
        self.directory.mkdir(parents=True, exist_ok=True)
        name = f"{uuid.uuid4().hex}{suffix}"
        (self.directory / name).write_bytes(data)
        return name

    async def load(self, name: str) -> bytes:
        path = self.directory / name
        # Names are generated by save(); refuse anything that could leave the directory.
        if Path(name).name != name or not path.is_file():
            raise StorageError("Proof file missing")
        return path.read_bytes()


class SupabaseStorage:
    def __init__(self, url: str, service_key: str, bucket: str, timeout: float = 15.0):
        self.base = f"{url.rstrip('/')}/storage/v1/object"
        self.bucket = bucket
        self.headers = {"Authorization": f"Bearer {service_key}", "apikey": service_key}
        self.timeout = timeout

    async def save(self, data: bytes, media_type: str, suffix: str) -> str:
        name = f"{uuid.uuid4().hex}{suffix}"
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.post(
                f"{self.base}/{self.bucket}/{name}",
                content=data,
                headers={**self.headers, "Content-Type": media_type, "x-upsert": "false"},
            )
        if resp.status_code not in (200, 201):
            raise StorageError(f"Upload failed ({resp.status_code})")
        return name

    async def load(self, name: str) -> bytes:
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.get(f"{self.base}/authenticated/{self.bucket}/{name}", headers=self.headers)
        if resp.status_code != 200:
            raise StorageError("Proof file missing")
        return resp.content


def get_storage() -> ProofStorage:
    s = get_settings()
    if s.storage_backend == "supabase":
        if not (s.supabase_url and s.supabase_service_key):
            raise RuntimeError("STORAGE_BACKEND=supabase needs SUPABASE_URL and SUPABASE_SERVICE_KEY")
        return SupabaseStorage(s.supabase_url, s.supabase_service_key, s.supabase_bucket)
    return LocalStorage(s.upload_dir)
